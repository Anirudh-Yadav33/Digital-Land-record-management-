// Public Search Ledger
app.get('/api/ledger/search', (req, res) => {
  const query = (req.query.q || '').toLowerCase().trim();
  const lands = db.getAllLands();

  if (!query) return res.json(lands);

  const filtered = lands.filter(
    l =>
      l.id.toLowerCase().includes(query) ||
      l.pin.toLowerCase().includes(query) ||
      l.title.toLowerCase().includes(query) ||
      l.ownerName.toLowerCase().includes(query) ||
      l.district.toLowerCase().includes(query) ||
      l.deedRef.toLowerCase().includes(query)
  );

  res.json(filtered);
});

