// Submit New Property Registration Application
app.post(
  '/api/registrations',
  authenticateToken,
  upload.fields([
    { name: 'idProofDoc', maxCount: 1 },
    { name: 'saleDeedDoc', maxCount: 1 },
    { name: 'surveyMapDoc', maxCount: 1 }
  ]),
  (req, res) => {
    try {
      const user = db.getUserById(req.user.id);
      const {
        propertyTitle,
        district,
        sector,
        areaSqFt,
        zone,
        proposedValuationUsd,
        sellerName,
        sellerIdNumber,
        previousDeedRef,
        coordinatesJson
      } = req.body;

      if (!propertyTitle || !district || !areaSqFt || !proposedValuationUsd) {
        return res.status(400).json({ error: 'Property title, district, area, and proposed valuation are required' });
      }

      // Parse coordinates if provided
      let parsedCoords = [];
      if (coordinatesJson) {
        try {
          parsedCoords = typeof coordinatesJson === 'string' ? JSON.parse(coordinatesJson) : coordinatesJson;
        } catch (e) {
          console.warn('Failed to parse coordinates json', e);
        }
      }

      // Process uploaded files
      const documents = [];
      if (req.files) {
        if (req.files.idProofDoc && req.files.idProofDoc[0]) {
          const f = req.files.idProofDoc[0];
          documents.push({
            id: 'doc_' + Date.now() + '_1',
            name: f.originalname,
            type: 'ID Proof',
            filename: f.filename,
            url: '/uploads/' + f.filename
          });
        }
        if (req.files.saleDeedDoc && req.files.saleDeedDoc[0]) {
          const f = req.files.saleDeedDoc[0];
          documents.push({
            id: 'doc_' + Date.now() + '_2',
            name: f.originalname,
            type: 'Sale Deed',
            filename: f.filename,
            url: '/uploads/' + f.filename
          });
        }
        if (req.files.surveyMapDoc && req.files.surveyMapDoc[0]) {
          const f = req.files.surveyMapDoc[0];
          documents.push({
            id: 'doc_' + Date.now() + '_3',
            name: f.originalname,
            type: 'Survey Map',
            filename: f.filename,
            url: '/uploads/' + f.filename
          });
        }
      }

      // Fallback sample docs if user uploaded none in demo UI
      if (documents.length === 0) {
        documents.push(
          { id: 'doc_demo_1', name: 'Citizen_ID_Certificate.pdf', type: 'ID Proof', url: '/uploads/sample_id.pdf' },
          { id: 'doc_demo_2', name: 'Property_Sale_Agreement.pdf', type: 'Sale Deed', url: '/uploads/sample_deed.pdf' },
          { id: 'doc_demo_3', name: 'Cadastral_Survey_Plan.pdf', type: 'Survey Map', url: '/uploads/sample_survey.pdf' }
        );
      }

      const appData = {
        id: 'APP-' + new Date().getFullYear() + '-' + Math.floor(1000 + Math.random() * 9000),
        applicantId: user.id,
        applicantName: user.name,
        applicantEmail: user.email,
        applicantIdNumber: user.idNumber,
        applicantPhone: user.phone,
        propertyTitle,
        district,
        sector: sector || 'General Sector',
        areaSqFt: Number(areaSqFt),
        zone: zone || 'Residential',
        proposedValuationUsd: Number(proposedValuationUsd),
        sellerName: sellerName || 'Previous Registered Owner',
        sellerIdNumber: sellerIdNumber || 'AD-7766-5544-3322',
        previousDeedRef: previousDeedRef || 'SALE-DEED-' + Math.floor(1000 + Math.random() * 9000),
        coordinates: parsedCoords,
        documents,
        status: 'PENDING',
        fraudRisk: null,
        submittedAt: new Date().toISOString(),
        inspectorNotes: null,
        reviewedAt: null,
        reviewedBy: null
      };

      // Automatically run Fraud Detection Engine on submission
      const existingLands = db.getAllLands();
      const fraudAudit = analyzeFraudRisk(appData, existingLands);
      appData.fraudRisk = fraudAudit;

      if (fraudAudit.level === 'CRITICAL' || fraudAudit.level === 'HIGH') {
        appData.status = 'FLAGGED_FRAUD';
      }

      db.createApplication(appData);
      db.addAuditLog(
        appData.status === 'FLAGGED_FRAUD' ? 'FRAUD_FLAGGED' : 'APPLICATION_SUBMITTED',
        user.email,
        `Submitted application ${appData.id} for property "${propertyTitle}". Status: ${appData.status} (Fraud Score: ${fraudAudit.score}/100)`
      );

      res.status(201).json({
        message: 'Property registration application submitted successfully',
        application: appData
      });
    } catch (err) {
      res.status(500).json({ error: 'Server error processing registration: ' + err.message });
    }
  }
);

