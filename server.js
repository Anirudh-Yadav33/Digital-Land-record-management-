// Get All Registration Applications (Admin)
app.get('/api/admin/applications', authenticateToken, requireAdmin, (req, res) => {
  const apps = db.getAllApplications();
  const existingLands = db.getAllLands();

  // Refresh fraud score calculation on the fly for complete accuracy
  const enrichedApps = apps.map(app => {
    if (!app.fraudRisk || app.status === 'PENDING') {
      app.fraudRisk = analyzeFraudRisk(app, existingLands);
    }
    return app;
  });

  res.json(enrichedApps);
});

// Trigger Fraud Risk Re-audit
app.post('/api/admin/applications/:id/fraud-check', authenticateToken, requireAdmin, (req, res) => {
  const appItem = db.getApplicationById(req.params.id);
  if (!appItem) return res.status(404).json({ error: 'Application not found' });

  const existingLands = db.getAllLands();
  const auditResult = analyzeFraudRisk(appItem, existingLands);

  let newStatus = appItem.status;
  if (auditResult.level === 'CRITICAL' || auditResult.level === 'HIGH') {
    newStatus = 'FLAGGED_FRAUD';
  } else if (appItem.status === 'FLAGGED_FRAUD') {
    newStatus = 'PENDING';
  }

  const updated = db.updateApplicationStatus(appItem.id, newStatus, appItem.inspectorNotes, req.user.email, auditResult);

  db.addAuditLog('FRAUD_AUDIT_EXECUTED', req.user.email, `Executed manual fraud audit on application ${appItem.id}. Score: ${auditResult.score}/100 (${auditResult.level})`);

  res.json({
    message: 'Fraud risk audit executed',
    fraudRisk: auditResult,
    application: updated
  });
});

// Admin Approve Registration -> Creates Registered Land Record & Certificate
